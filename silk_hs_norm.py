"""طبقةُ التنميط العربية الواحدة — the ONE Arabic normalization layer.

> **العائلة.** `two-normalizers-one-pipeline`: كان في المستودع تنميطان
> مختلفان على نفس المسار — `silk_hs_resolver._norm` يخفض حالةَ الأحرف فقط،
> و`silk_hs_confirm._norm` يطوي الألفَ والياءَ والتاءَ المربوطة. فكان المرجعُ
> يعوّض الفارقَ **بالبيانات**: الصفّ 170490 يحمل «حلاوة طحينية» و«حلاوه
> طحينيه» معاً لأن المُحلِّل لا يعرف أنهما واحد. تنميطٌ ناقصٌ يُدفَع ثمنُه
> صفّاً صفّاً إلى الأبد.
>
> **القاعدة الدائمة.** تنميطٌ واحد يستورده **كلُّ** مسار تصنيف: المُحلِّل،
> بوّابةُ التطابق الدلالي، خطُّ التصنيف، وطبقةُ العرض. أيُّ تنميطٍ ثانٍ
> يُكتَب في هذا المستودع عيبٌ لا ميزة.

One normalizer, imported by every classification path — the resolver, the
semantic gate, the pipeline and the view layer. A second normalizer anywhere in
this repository is a defect, not a feature.

المكتبات: stdlib فقط (`re`) — لا شبكة، لا تبعية، يُستورَد بلا مفاتيح.
"""
from __future__ import annotations

import functools
import re

# ── التشكيل والتطويل · diacritics + tatweel ─────────────────────────────────
# النطاق يشمل: الفتحتين/الضمتين/الكسرتين والسكون والشدّة (064B–0652)، والألف
# الخنجرية (0670)، وعلاماتِ الوقف القرآنية (0617–061A)، والتطويلَ (0640).
_DIACRITICS = re.compile(r"[ؗ-ًؚ-ْٰـ]")

# ── طيُّ الحروف · letter folding ─────────────────────────────────────────────
# همزاتُ الألف ووصلُها => ألفٌ عارية؛ الألفُ المقصورة => ياء؛ التاءُ المربوطة
# => هاء؛ وهمزتا الواو والياء => حرفاهما. هذه تهجئاتٌ لنفس الكلمة عند الكاتب
# العربيّ العاديّ، لا كلماتٌ مختلفة — وهي بالضبط ما كان المرجع يكرّره يدوياً.
_FOLD = str.maketrans({
    "أ": "ا", "إ": "ا", "آ": "ا", "ٱ": "ا", "ٰ": "ا",
    "ى": "ي", "ئ": "ي",
    "ة": "ه",
    "ؤ": "و",
})

# الأرقامُ العربية-الهندية (شرقية وفارسية) => لاتينية، كي تتطابق العتباتُ
# الرقمية في أسماء المنتجات مع أوصاف المرجع («٣٪» و«3%» رقمٌ واحد).
_DIGITS = str.maketrans("٠١٢٣٤٥٦٧٨٩۰۱۲۳۴۵۶۷۸۹", "01234567890123456789")

# فواصلُ الوحدات — كلُّ ما ليس حرفاً ولا رقماً يفصل، بلا استثناءات مدفونة.
_SPLIT = re.compile(r"[^\wء-ي]+", re.UNICODE)
_WS = re.compile(r"\s+")

# نطاقُ الحروف العربية الأساسية (للفحص `is_arabic`).
_ARABIC_CHAR = re.compile(r"[ء-ي]")

# كلماتُ الربط والأدوات — تُستبعَد من الوحدات ذاتِ المعنى. عربيٌّ وإنجليزيّ
# معاً لأن وصفَ المرجع إنجليزيٌّ واسمَ المنتج عربيّ، والمطابقةُ تجري بينهما.
# **نُقِلت كما هي** من `silk_hs_confirm._STOPWORDS` (نقطةُ الحقيقة السابقة)
# كي لا يتغيّر سلوكُ البوّابة مع توحيد التنميط.
STOPWORDS: frozenset[str] = frozenset({
    "و", "من", "في", "علي", "عن", "مع", "او", "ذو", "ذات", "هذا",
    "the", "of", "and", "or", "with", "for", "in", "a", "an", "to",
    "fresh", "dried", "other", "n.e.c", "nec", "prepared", "preserved",
})

# طولُ الكلمة الذي يُسقَط عنده «أل» التعريف — دونه قد تكون «ال» أصلاً من
# الكلمة نفسها («ألم»، «الف»). القيمةُ منقولةٌ حرفياً من السلوك السابق.
_AL_MIN_LEN = 5


def normalize(text: object) -> str:
    """طبّع نصاً للمطابقة — تنميطٌ كاملٌ واحد لكل المسارات.

    يزيل التشكيلَ والتطويل، ويطوي الهمزاتِ والألفَ المقصورةَ والتاءَ المربوطة،
    ويحوّل الأرقامَ العربية-الهندية، ويخفض حالةَ الأحرف اللاتينية، ويوحّد
    المسافات. **لا يحذف** الترقيمَ من النصّ (ذلك عملُ `tokens`) كي يبقى
    التطابقُ الحرفيُّ الكامل ممكناً على العبارات المركّبة.
    """
    s = str(text or "").strip().lower()
    if not s:
        return ""
    s = _DIACRITICS.sub("", s)
    s = s.translate(_FOLD).translate(_DIGITS)
    return _WS.sub(" ", s).strip()


def tokens(text: object) -> list[str]:
    """قسّم نصاً إلى وحداتٍ ذاتِ معنى — مُنمَّطة، بلا «أل» ولا أدوات ربط.

    الترتيبُ محفوظ (بعضُ المستدعين يقرأ الوحدةَ الأولى بوصفها الرأس)، والتكرار
    محفوظٌ أيضاً — من أراد مجموعةً فليأخذ `token_set`.
    """
    out: list[str] = []
    for raw in _SPLIT.split(normalize(text)):
        t = raw.strip()
        if not t:
            continue
        if t.startswith("ال") and len(t) > _AL_MIN_LEN - 1:
            t = t[2:]
        # طيُّ الجمع الإنجليزيّ: وحدةٌ لاتينية (ASCII حصراً — فلا تُمَسّ
        # العربيةُ وعائلةُ «رقي»/«ورقية»، الدرس 211) بطول ≥ 4 تنتهي بـ«s»
        # ⇒ تُحذَف الـ«s» الأخيرةُ **فقط** (cheeses→cheese, dates→date) —
        # لا حذفَ «es» كاملةً (يحوّل cheeses إلى chees فيكسر الحالةَ نفسَها).
        # فيبقى الجمعُ ومفردُه وحدةَ قياسٍ واحدة كما «حلاوة»/«حلاوه»، والوحدةُ
        # الكاملة تبقى وحدةَ القياس (البند ٨ نافذ — لا احتواءَ حرفياً).
        # **هنا لا في `normalize()`**: تلك تضمن المطابقةَ الحرفية للعبارة
        # الكاملة وتغذّي مفاتيحَ difflib الضبابية (silk_hs_resolver._index) —
        # الطيُّ فيها يحرّك الدرجاتِ الضبابية في المستودع كله.
        if t.isascii() and len(t) >= 4 and t.endswith(("s", "S")):
            t = t[:-1]
        if len(t) < 2 or t in STOPWORDS:
            continue
        out.append(t)
    return out


@functools.lru_cache(maxsize=4096)
def token_set(text: str) -> frozenset[str]:
    """مجموعةُ وحدات النصّ — مُخزَّنة، فالمرجعُ يُنمَّط مرّةً لا مرّةً لكل طلب."""
    return frozenset(tokens(text))


def is_arabic(text: object) -> bool:
    """هل يحمل النصُّ حرفاً عربياً واحداً على الأقل؟"""
    return bool(_ARABIC_CHAR.search(str(text or "")))


def same_token(a: object, b: object) -> bool:
    """هل الوحدتان **الوحدةُ نفسُها** بعد التنميط؟

    هذه هي القاعدةُ التي حلّت محلّ `x in y`: «رقي» و«ورقية» وحدتان مختلفتان
    مهما تشابهت حروفُهما، و«حلاوة»/«حلاوه» وحدةٌ واحدة مهما اختلف رسمُها.
    """
    return normalize(a) == normalize(b) and bool(normalize(a))
