def _digits(hs: object) -> str:
    return "".join(ch for ch in str(hs or "") if ch.isdigit())


def definition(hs: object) -> "str | None":
    """تعريف البند من المرجع الداخلي — السداسي أولاً ثم الرباعي، وإلا None
    (بندٌ خارج المرجع = غياب معلَن، لا اختلاق تعريف)."""
    d = _digits(hs)
    if len(d) >= 6 and d[:6] in _HS6:
        return _HS6[d[:6]]
    if len(d) >= 4 and d[:4] in _HEADINGS:
        return _HEADINGS[d[:4]]
    return None


def definition_line(hs: object) -> "str | None":
    """سطرُ التعريف الجاهز للحقن في موجّه الكاتب — أو None خارج المرجع."""
    de = definition(hs)
    if not de:
        return None
    d = _digits(hs)
    code = d[:6] if len(d) >= 6 and d[:6] in _HS6 else d[:4]
    return f"HS {code}: {de} (تسميات النظام المنسَّق WCO HS 2022)"
