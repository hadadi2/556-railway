-- Additive opportunity workflow. CREATE IF NOT EXISTS supports the local preview.
CREATE TABLE IF NOT EXISTS export_opportunities (
    id INTEGER PRIMARY KEY,
    account_id INTEGER NOT NULL,
    product_id INTEGER NOT NULL,
    exporter TEXT NOT NULL,
    market TEXT NOT NULL,
    hs_code TEXT NOT NULL,
    market_name TEXT NOT NULL,
    snapshot TEXT NOT NULL,
    notes TEXT NOT NULL DEFAULT '',
    study_id INTEGER,
    created_at TEXT NOT NULL,
    UNIQUE(account_id, product_id, exporter, market, hs_code)
);
ALTER TABLE export_opportunities ADD COLUMN archived_at TEXT;
ALTER TABLE export_opportunities ADD COLUMN study_requested_at TEXT;
CREATE INDEX IF NOT EXISTS ep_account_page ON export_opportunities(account_id, archived_at, id DESC);
CREATE INDEX IF NOT EXISTS ep_study_link ON export_opportunities(study_id);
CREATE TABLE IF NOT EXISTS export_opportunity_events (
    id INTEGER PRIMARY KEY, account_id INTEGER NOT NULL,
    kind TEXT NOT NULL, created_at TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS ep_events_date ON export_opportunity_events(created_at, kind);
CREATE TABLE IF NOT EXISTS export_opportunity_source_status (
    id INTEGER PRIMARY KEY CHECK(id=1),
    last_success_at TEXT, last_failure_at TEXT, last_retrieved_at TEXT,
    cached INTEGER
);
CREATE TABLE IF NOT EXISTS export_opportunity_rate_windows (
    account_id INTEGER PRIMARY KEY, window_start INTEGER NOT NULL, hits INTEGER NOT NULL
);

