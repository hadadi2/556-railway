-- 025 — التكاليفُ الثابتة على بطاقة المنتج · product fixed costs (تقرير ٧ §3.5).
--
-- **الفجوة:** «نقطة التعادل» كانت كلفةَ الدخول ÷ هامش الوحدة — استردادُ نقد
-- الشحنة التجريبية لا التعادلُ التشغيليّ. التعادلُ التشغيليّ = التكاليفُ
-- الثابتة ذات الصلة ÷ هامش المساهمة، ولا مدخلَ للتكاليف الثابتة في البطاقة.
--
-- **ولا قيمةَ افتراضية.** التكاليفُ الثابتة رقمُ المصنع نفسه (فجوةُ إدخال لا
-- فجوةُ بحث) — `NULL` تعني «لم يُدخِلها المصنع» ويبقى التعادلُ التشغيليّ فجوةً
-- معلنة تسمّي بنودها. إضافي فقط — لا مساس بأي صف قائم. Additive only.
ALTER TABLE products ADD COLUMN fixed_costs REAL;
-- ومراجعة §58: هامشُ المساهمة طرحٌ بين تكلفة المصنع وأقصى سعر مصنع منافس،
-- ولا طرحَ بين عملتين بلا تصريح — والبطاقةُ لم تكن تحمل عملةَ التكلفة أصلاً،
-- فلا هامشَ يُحسب على أيّ مسارٍ حيّ. رمزُ ISO كما يصرّح به المصنع؛ `NULL`
-- = «لم يُصرِّح» ويبقى البندُ فجوةً تسمّي العملة.
ALTER TABLE products ADD COLUMN cost_currency TEXT;
