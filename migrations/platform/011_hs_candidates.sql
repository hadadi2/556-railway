-- ترحيل ٠١١: مرشّحو البند الجمركي على صفّ الدراسة · HS candidates on the study row.
--
-- لماذا (بلاغ المالك 2026-08-19 «المحرّك لا يعمل»، أُعيد إنتاجه محلياً): دراسة
-- «حليب» تُطلق ثم يرفضها المحرّك خلال ثانية ببوّابة البند الجمركي: «اختر البند
-- المطابق أدناه» — والمرشّحون كانوا يُفقَدون عند حدّ الجسر (نصّ الرسالة وحده
-- يُحفَظ)، فلا «أدناه» في أي شاشة: طريق مسدود بلا مخرج.
-- هذا العمود يحفظ حمولة المرشّحين كما ولّدها المحرّك (JSON) كي تعرضها الواجهة
-- ويختار المصنع بندَه ثم يعيد الإطلاق. يُمسَح عند كل مطالبة إطلاق جديدة.
-- The refusal payload's candidates were dropped at the bridge boundary; without
-- them the factory had nothing to choose from. Cleared on every new launch claim.
ALTER TABLE studies ADD COLUMN hs_candidates TEXT;

-- ورايةُ «اختار المصنعُ بندَه من القائمة المعروضة» — the factory's explicit pick.
-- بلا هذه الراية كانت الحلقة تُغلَق على نفسها: المصنع يختار البند، فتعيد بوّابةُ
-- التأكيد رفضَه بالرسالة ذاتها (البوّابة تسأل عن تأكيدٍ بشري، والاختيار كان
-- يضيع بين النقرة والمحرّك). تُرفَع فقط حين يطابق الرمزُ المُختار أحدَ
-- المرشّحين المعروضين — الكتابةُ اليدوية العمياء تبقى محكومة بالبوّابة.
ALTER TABLE studies ADD COLUMN hs_confirmed INTEGER NOT NULL DEFAULT 0;

-- رمزُ التشغيلة — هويّةُ محاولةِ إطلاقٍ بعينها · a launch attempt's identity.
-- بلا هذا: تشغيلةٌ تجاوزت مهلتها تُكنَس وتعود الدراسةُ مسودّة، فيعيد المصنع
-- الإطلاق — ثم يستيقظ خيطُ التشغيلة القديمة («الزومبي») فيجد الصفَّ
-- `in_progress` ثانيةً ويكتب عليه نتيجتَه هو (معرّف تحليلٍ قديم، أو إفشالُ
-- تشغيلةٍ سليمة وإرجاعُ حصّتها). الشرطُ `AND run_token = ?` في كل إنهاء يجعل
-- الكتابة مملوكةً لصاحبها وحده. Every finish is scoped to its own attempt.
ALTER TABLE studies ADD COLUMN run_token TEXT;
