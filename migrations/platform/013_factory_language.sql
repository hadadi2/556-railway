-- 012 — لغة المصنع تحكم لغة التقرير · factory language controls report language.
--
-- المشكلة (فحص 2026-08-20): لا يوجد إعداد لغة على مستوى **المصنع** إطلاقاً.
-- الموجود `users.language_preference` (الترحيل 001) + `users.language_chosen_at`
-- (الترحيل 008) وكلاهما معرَّف صراحةً في وثيقتيهما **لغة واجهة لكل مستخدم**،
-- يُكتب من `PATCH /platform/me/language` حصراً ولا يقرؤه أيّ مسار تقرير. ونقاط
-- التقرير الثلاث (`/studies/{id}/report[.docx|.pdf]`) تنادي `build_view` بلا
-- لغة — فالمصنع الإنجليزيّ يحصل على هيكلٍ إنجليزيّ حول تقريرٍ عربيّ بالكامل.
--
-- القرار: يُضاف الإعداد إلى **نموذج إعدادات المصنع نفسه** باسمٍ عامّ لا باسمٍ
-- خاصٍّ بالتقرير (فلغة المصنع شأنٌ أوسع من مخرَجٍ واحد)، بنفس اسم عمود
-- المستخدمين وقيده وسِمَته الزمنية — تناسقاً مع المخطّط القائم لا اختراعاً
-- لنمطٍ ثانٍ. **لا** `accounts.report_language`، و**لا** إعادة استعمال عمود
-- المستخدمين مصدراً للغة التقرير.
--
-- الافتراضي `'ar'` لا `'en'` (قرار المالك 2026-08-20): كل تقارير المصانع
-- القائمة عربية فعلاً، وقلبها صامتاً إلى الإنجليزية تغييرُ منتجٍ بلا اختيار.
-- ودلالة `language_chosen_at` هي نفسها المثبتة في الترحيل 008: NULL = لم
-- يُختَر قطّ، وقيمة = اختيارٌ صريح كتبه مسار الاختيار الوحيد.
--
-- واللقطة على الدراسة: لغة التقرير تُختَم **وقت المطالبة الذرّية** (نفس جملة
-- `run_token`) فلا تنتج تشغيلةٌ حيّة تقريراً مختلط اللغة حين يبدّل المصنع
-- إعداده أثناءها؛ و`factory_language_at_generation` يحفظ ما كان عليه إعداد
-- المصنع لحظتَها، فيُقرأ التقرير القديم لاحقاً بسياقه الصحيح.
--
-- إضافي فقط (قاعدة الترحيلات): لا DROP ولا DELETE ولا تعديل صفٍّ قائم.
ALTER TABLE accounts ADD COLUMN language_preference TEXT NOT NULL DEFAULT 'ar'
    CHECK (language_preference IN ('ar','en'));
ALTER TABLE accounts ADD COLUMN language_chosen_at TEXT;

ALTER TABLE studies  ADD COLUMN report_language TEXT;
ALTER TABLE studies  ADD COLUMN factory_language_at_generation TEXT;
